func TestSharedQuickSendScopeWireCompatibility(t *testing.T) {
	for n, scope := range sharedSendScopes {
		cfg := DefaultConfig()
		cfg.Settings.QuickSendScope = scope
		prefs := preferencesForShared(cfg)
		var number int
		if err := json.Unmarshal(prefs["quickSendScope"], &number); err != nil || number != n {
			t.Fatal("not Swift Int", scope, err)
		}
		d := SharedDocument{Preferences: prefs}
		got, err := d.Configuration()
		if err != nil || got.Settings.QuickSendScope != scope {
			t.Fatal(scope, err)
		}
		legacy, _ := json.Marshal(scope)
		d.Preferences["quickSendScope"] = legacy
		got, err = d.Configuration()
		if err != nil || got.Settings.QuickSendScope != scope {
			t.Fatal("legacy rejected", scope, err)
		}
	}
	for _, raw := range []string{`null`, `7`, `-1`, `1.5`, `true`, `"bogus"`} {
		if _, err := decodeSharedQuickSendScope([]byte(raw)); err == nil {
			t.Fatal("invalid scope accepted", raw)
		}
	}
}
func TestLegacySharedProtocolUpgradesWithoutConflictOrCredentialLoss(t *testing.T) {
	ctx := context.Background()
	e, cfg, master := syncEngineFixture(t, t.TempDir())
	if err := e.Vault.Put(cfg.Profiles[0], "fixture-secret"); err != nil {
		t.Fatal(err)
	}
	plan, err := e.Prepare(ctx, cfg, master, true)
	if err != nil {
		t.Fatal(err)
	}
	cfg, err = plan.Commit(ctx, nil, master)
	if err != nil {
		t.Fatal(err)
	}
	object, err := e.Transport.Fetch(ctx)
	if err != nil {
		t.Fatal(err)
	}
	doc, err := DecodeSharedDocument(object.Data, master)
	if err != nil {
		t.Fatal(err)
	}
	doc.Preferences["quickSendScope"] = json.RawMessage(`"current"`)
	plain, err := json.Marshal(doc)
	if err != nil {
		t.Fatal(err)
	}
	legacy, err := SealShared(plain, master)
	if err != nil {
		t.Fatal(err)
	}
	if err = e.Transport.Put(ctx, legacy, object.ETag); err != nil {
		t.Fatal(err)
	}
	plan, err = e.Prepare(ctx, cfg, master, false)
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.Conflicts) != 0 || plan.InitialChoiceRequired {
		t.Fatal("encoding change introduced conflict")
	}
	cfg, err = plan.Commit(ctx, nil, master)
	if err != nil {
		t.Fatal(err)
	}
	object, err = e.Transport.Fetch(ctx)
	if err != nil {
		t.Fatal(err)
	}
	doc, err = DecodeSharedDocument(object.Data, master)
	if err != nil || string(doc.Preferences["quickSendScope"]) != "0" {
		t.Fatal("legacy not upgraded", err)
	}
	if secret, err := e.Vault.GetFor(cfg.Profiles[0], cfg.Profiles[0].Identity()); err != nil || secret != "fixture-secret" {
		t.Fatal("credential lost", err)
	}
}

