"""Embed only a clean, verified Windows build's resources, never user data."""
from contextlib import contextmanager
import hashlib
import json
from pathlib import Path
import zipfile


@contextmanager
def embedded_resources(root, product):
    root, product = Path(root), Path(product)
    manifest = json.loads((root / 'internal/terminal/mygo-plugin.json').read_text())
    native = next(lib for lib in manifest['libraries'] if lib['name'] == 'libghostty-vt')['files']['windows-amd64']
    dll = product / native['name']
    if hashlib.sha256(dll.read_bytes()).hexdigest() != native['sha256']:
        raise RuntimeError('Embedded terminal DLL checksum mismatch')
    package = root / 'internal/bundled'
    archive = package / 'payload_windows_amd64.zip'
    generated = package / 'payload_windows_amd64.go'
    if archive.exists() or generated.exists():
        raise RuntimeError('An embedded-resource build is already in progress; generated files were preserved')
    forbidden = {'config.json', 'credentials.json', 'credential-key', 'known_hosts', 'state-transaction.json', 'storage-location.json'}
    files = []
    for file in sorted(product.rglob('*')):
        if file.is_symlink():
            raise RuntimeError('Embedded resources cannot contain symlinks')
        if not file.is_file():
            continue
        relative = file.relative_to(product)
        if file.name.lower() in forbidden or any(part.startswith('.') for part in relative.parts):
            raise RuntimeError('User data cannot be embedded in the executable')
        if file.suffix.lower() == '.exe':
            continue
        files.append((file, relative.as_posix()))
    try:
        with zipfile.ZipFile(archive, 'x', zipfile.ZIP_DEFLATED) as z:
            for file, name in files:
                info = zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(info, file.read_bytes())
        generated.write_text('''// Code generated by scripts/single_file.py; DO NOT EDIT.
package bundled

import _ "embed"

//go:embed payload_windows_amd64.zip
var windowsPayload []byte

func init() { payload = windowsPayload }
''', encoding='utf-8')
        yield
    finally:
        generated.unlink(missing_ok=True)
        archive.unlink(missing_ok=True)
