#!/usr/bin/env python3
"""Generate/check the native Swift copy of the single shared field contract."""
import argparse, hashlib, json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--native-source',type=Path,required=True)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
data=(ROOT/'internal/core/shared_configuration_schema.json').read_text(encoding='utf-8')
contract=json.loads(data)
def validate(rule):
    allowed={'type','keys','ref','required','nullable','default','values','items','mapOf','minimum','maximum','minItems','maxItems','pattern'}
    if set(rule)-allowed: raise SystemExit('Unsupported contract keyword: '+str(set(rule)-allowed))
    if rule.get('type') not in {'object','array','string','boolean','integer','number'}:raise SystemExit('Unsupported field type')
    if 'ref' in rule and rule['ref'] not in contract['definitions']:raise SystemExit('Unknown contract reference')
    for child in ('items','mapOf'):
        if child in rule:validate(rule[child])
for fields in contract['definitions'].values():
    for rule in fields.values():validate(rule)
sha=hashlib.sha256(data.encode()).hexdigest()
text='// Generated by oshell-desktop/scripts/sync-configuration-contract.py; do not edit.\n// SHA256: '+sha+'\nlet sharedConfigurationContract = #"""\n'+data+'"""#\n'
target=args.native_source/'Sources/OShellCore/SharedConfigurationContract.swift'
if args.check:
 if not target.exists() or target.read_text(encoding='utf-8')!=text:raise SystemExit('Shared configuration contract differs between projects; regenerate and test both.')
else:target.write_text(text,encoding='utf-8',newline='\n')
print('Shared configuration contract SHA256:',sha)
